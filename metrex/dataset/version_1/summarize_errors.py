import pandas as pd
import matplotlib.pyplot as plt

df = pd.read_csv("syntax_results/veri_error_counts_total.csv")

plt.figure(figsize=(14,6))
plt.bar(df["veri_code"], df["total_count"])
plt.yscale("log")
plt.ylabel("Number of Errors (log scale)")
plt.xlabel("VERI Error Code")
plt.title("Distribution of Jasper VERI Errors (Log Scale)")
plt.xticks(rotation=60, ha="right")
plt.tight_layout()
plt.tight_layout()
plt.savefig("syntax_results/veri_error_counts.png", dpi=300)
plt.close()
