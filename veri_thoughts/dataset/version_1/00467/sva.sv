module four_bit_adder_sva (
    input logic       clk,
    input logic [3:0] A,
    input logic [3:0] B,
    input logic [4:0] C,
    input logic       CO
);

    // The 5-bit output vector must equal the unsigned sum of A and B.
    check_total_sum: assert property (
        @(posedge clk) C == ({1'b0, A} + {1'b0, B})
    );

    // The separate carry output must match the MSB of C.
    check_co_matches_c_msb: assert property (
        @(posedge clk) CO == C[4]
    );

    // Bit 0 sum is the XOR of A[0] and B[0] with no carry-in.
    check_bit0_sum: assert property (
        @(posedge clk) C[0] == (A[0] ^ B[0])
    );

    // Bit 1 sum includes the carry generated by bit 0.
    check_bit1_sum: assert property (
        @(posedge clk) C[1] == (A[1] ^ B[1] ^ (A[0] & B[0]))
    );

    // Bit 2 sum includes the ripple carry from bits 0 and 1.
    check_bit2_sum: assert property (
        @(posedge clk) C[2] == (A[2] ^ B[2] ^
                                ((A[1] & B[1]) |
                                 ((A[0] & B[0]) & (A[1] ^ B[1]))))
    );

    // Bit 3 sum includes the ripple carry from bits 0 through 2.
    check_bit3_sum: assert property (
        @(posedge clk) C[3] == (A[3] ^ B[3] ^
                                ((A[2] & B[2]) |
                                 (((A[1] & B[1]) |
                                   ((A[0] & B[0]) & (A[1] ^ B[1]))) &
                                  (A[2] ^ B[2]))))
    );

    // Carry-out follows the final full-adder carry equation.
    check_final_carry: assert property (
        @(posedge clk) CO == ((A[3] & B[3]) |
                              (((A[2] & B[2]) |
                                (((A[1] & B[1]) |
                                  ((A[0] & B[0]) & (A[1] ^ B[1]))) &
                                 (A[2] ^ B[2]))) &
                               (A[3] ^ B[3])))
    );

endmodule