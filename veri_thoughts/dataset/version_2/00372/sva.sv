module two_bit_adder_sva (
    input logic       clk,
    input logic [1:0] A,
    input logic [1:0] B,
    input logic       cin,
    input logic [1:0] sum,
    input logic       cout
);

    // Combined output must equal A + B + cin.
    check_total_addition: assert property (
        @(posedge clk) disable iff (1'b0)
        ({cout, sum} == ({1'b0, A} + {1'b0, B} + cin))
    );

    // The LSB sum bit matches the first full-adder sum equation.
    check_lsb_sum: assert property (
        @(posedge clk) disable iff (1'b0)
        (sum[0] == (A[0] ^ B[0] ^ cin))
    );

    // The MSB sum bit uses the carry generated by the LSB stage.
    check_msb_sum: assert property (
        @(posedge clk) disable iff (1'b0)
        (sum[1] == (A[1] ^ B[1] ^ ((A[0] & B[0]) | (A[0] & cin) | (B[0] & cin))))
    );

    // The final carry-out matches the upper full-adder carry equation.
    check_cout_function: assert property (
        @(posedge clk) disable iff (1'b0)
        (cout == ((A[1] & B[1]) |
                  (A[1] & ((A[0] & B[0]) | (A[0] & cin) | (B[0] & cin))) |
                  (B[1] & ((A[0] & B[0]) | (A[0] & cin) | (B[0] & cin)))))
    );

    // Adding zero with no carry-in passes A through unchanged.
    check_a_passthrough: assert property (
        @(posedge clk) disable iff (1'b0)
        ((B == 2'b00) && (cin == 1'b0)) |-> ((sum == A) && (cout == 1'b0))
    );

    // Adding zero with no carry-in passes B through unchanged.
    check_b_passthrough: assert property (
        @(posedge clk) disable iff (1'b0)
        ((A == 2'b00) && (cin == 1'b0)) |-> ((sum == B) && (cout == 1'b0))
    );

    // A carry-in alone increments the zero input case by one.
    check_cin_only_increment: assert property (
        @(posedge clk) disable iff (1'b0)
        ((A == 2'b00) && (B == 2'b00) && (cin == 1'b1)) |-> ((sum == 2'b01) && (cout == 1'b0))
    );

endmodule