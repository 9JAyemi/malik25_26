module ripple_carry_adder_sva (
    input logic [3:0] a,
    input logic [3:0] b,
    input logic       cin,
    input logic [3:0] sum,
    input logic       cout
);

    // Sum matches the RTL arithmetic assignment.
    check_sum_matches_add: assert property (
        @($global_clock) sum == (a + b + cin)
    );

    // sum[0] is the XOR of the LSB inputs and cin.
    check_sum_bit0: assert property (
        @($global_clock) sum[0] == (a[0] ^ b[0] ^ cin)
    );

    // sum[1] uses the carry generated from bit 0.
    check_sum_bit1: assert property (
        @($global_clock)
        sum[1] == (
            a[1] ^ b[1] ^
            ((a[0] & b[0]) | (a[0] & cin) | (b[0] & cin))
        )
    );

    // sum[2] uses the carry generated from bits 0 and 1.
    check_sum_bit2: assert property (
        @($global_clock)
        sum[2] == (
            a[2] ^ b[2] ^
            ((a[1] & b[1]) |
             (a[1] & ((a[0] & b[0]) | (a[0] & cin) | (b[0] & cin))) |
             (b[1] & ((a[0] & b[0]) | (a[0] & cin) | (b[0] & cin))))
        )
    );

    // cout is the carry generated by the lower three bits.
    check_cout_lower3_carry: assert property (
        @($global_clock)
        cout == (({1'b0, a[2:0]} + {1'b0, b[2:0]} + cin) >= 4'd8)
    );

    // sum[3] uses cout as the carry-in to the MSB.
    check_sum_bit3_uses_cout: assert property (
        @($global_clock) sum[3] == (a[3] ^ b[3] ^ cout)
    );

endmodule