module adder_sva (
    input logic       clk,
    input logic [3:0] A,
    input logic [3:0] B,
    input logic       Cin,
    input logic [3:0] Sum,
    input logic       Cout
);

    function automatic logic fa_sum (
        input logic a,
        input logic b,
        input logic cin
    );
        fa_sum = a ^ b ^ cin;
    endfunction

    function automatic logic fa_carry (
        input logic a,
        input logic b,
        input logic cin
    );
        fa_carry = (a & b) | (a & cin) | (b & cin);
    endfunction

    // The 5-bit output must equal A + B + Cin.
    check_total_sum: assert property (
        @(posedge clk) {Cout, Sum} == ({1'b0, A} + {1'b0, B} + Cin)
    );

    // Sum[0] must match the first full-adder sum equation.
    check_bit0_sum: assert property (
        @(posedge clk) Sum[0] == fa_sum(A[0], B[0], Cin)
    );

    // Sum[1] must use the carry generated by bit 0.
    check_bit1_sum: assert property (
        @(posedge clk) Sum[1] == fa_sum(A[1], B[1], fa_carry(A[0], B[0], Cin))
    );

    // Sum[2] must use the ripple carry from bits 0 and 1.
    check_bit2_sum: assert property (
        @(posedge clk) Sum[2] == fa_sum(
            A[2],
            B[2],
            fa_carry(A[1], B[1], fa_carry(A[0], B[0], Cin))
        )
    );

    // Sum[3] must use the ripple carry from bits 0 through 2.
    check_bit3_sum: assert property (
        @(posedge clk) Sum[3] == fa_sum(
            A[3],
            B[3],
            fa_carry(A[2], B[2], fa_carry(A[1], B[1], fa_carry(A[0], B[0], Cin)))
        )
    );

    // Cout must match the final ripple-carry output.
    check_final_carry: assert property (
        @(posedge clk) Cout == fa_carry(
            A[3],
            B[3],
            fa_carry(A[2], B[2], fa_carry(A[1], B[1], fa_carry(A[0], B[0], Cin)))
        )
    );

    // Adding zero with no carry-in must pass A through unchanged.
    check_add_zero_to_a: assert property (
        @(posedge clk) (B == 4'b0000 && Cin == 1'b0) |-> (Sum == A && Cout == 1'b0)
    );

    // Adding zero with no carry-in must pass B through unchanged.
    check_add_zero_to_b: assert property (
        @(posedge clk) (A == 4'b0000 && Cin == 1'b0) |-> (Sum == B && Cout == 1'b0)
    );

endmodule