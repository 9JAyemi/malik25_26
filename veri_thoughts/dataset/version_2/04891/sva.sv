module ripple_carry_adder_sva (
    input logic clk,
    input logic [3:0] S,
    input logic [3:0] A,
    input logic [3:0] B,
    input logic Cout
);

    function automatic logic carry3(input logic x, input logic y, input logic z);
        carry3 = (x & y) | (x & z) | (y & z);
    endfunction

    function automatic logic [3:0] sum4(input logic [3:0] x, input logic [3:0] y, input logic cin);
        sum4 = x + y + cin;
    endfunction

    // No clock or reset exists in the RTL; assertions are sampled on external clk.

    // S must equal the 4-bit sum of A, B, and the input carry.
    check_sum_matches_truncated_add: assert property (
        @(posedge clk) S == sum4(A, B, Cout)
    );

    // Bit 0 must match a full-adder sum with the input carry.
    check_bit0_sum: assert property (
        @(posedge clk) S[0] == (A[0] ^ B[0] ^ Cout)
    );

    // Bit 1 must use the carry generated by bit 0.
    check_bit1_uses_carry_from_bit0: assert property (
        @(posedge clk) S[1] == (A[1] ^ B[1] ^ carry3(A[0], B[0], Cout))
    );

    // Bit 2 must use the carry generated by bit 1.
    check_bit2_uses_carry_from_bit1: assert property (
        @(posedge clk) S[2] == (A[2] ^ B[2] ^ carry3(A[1], B[1], carry3(A[0], B[0], Cout)))
    );

    // Bit 3 must use the carry generated by bit 2.
    check_bit3_uses_carry_from_bit2: assert property (
        @(posedge clk) S[3] == (A[3] ^ B[3] ^ carry3(A[2], B[2], carry3(A[1], B[1], carry3(A[0], B[0], Cout))))
    );

    // With stable inputs across samples, the output must remain stable.
    check_output_stable_when_inputs_stable: assert property (
        @(posedge clk) ($stable(A) && $stable(B) && $stable(Cout)) |-> $stable(S)
    );

endmodule