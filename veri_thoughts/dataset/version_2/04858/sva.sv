module four_bit_adder_sva (
    input logic [3:0] A,
    input logic [3:0] B,
    input logic       C_in,
    input logic [3:0] S,
    input logic       C_out
);

    // Combinational DUT; assertions are sampled on the formal global clock.
    function automatic logic fa_carry (
        input logic a,
        input logic b,
        input logic cin
    );
        fa_carry = (a & b) | ((a ^ b) & cin);
    endfunction

    // 5-bit result matches A + B + C_in.
    check_total_sum: assert property (
        @($global_clock) {C_out, S} == ({1'b0, A} + {1'b0, B} + C_in)
    );

    // Bit 0 sum is the XOR of A[0], B[0], and C_in.
    check_sum_bit0: assert property (
        @($global_clock) S[0] == (A[0] ^ B[0] ^ C_in)
    );

    // Bit 1 sum uses the carry generated by bit 0.
    check_sum_bit1: assert property (
        @($global_clock) S[1] == (A[1] ^ B[1] ^ fa_carry(A[0], B[0], C_in))
    );

    // Bit 2 sum uses the carry generated by bit 1.
    check_sum_bit2: assert property (
        @($global_clock) S[2] == (A[2] ^ B[2] ^ fa_carry(A[1], B[1], fa_carry(A[0], B[0], C_in)))
    );

    // Bit 3 sum uses the carry generated by bit 2.
    check_sum_bit3: assert property (
        @($global_clock) S[3] == (A[3] ^ B[3] ^ fa_carry(A[2], B[2], fa_carry(A[1], B[1], fa_carry(A[0], B[0], C_in))))
    );

    // Carry-out matches the final ripple-carry stage.
    check_carry_out: assert property (
        @($global_clock) C_out == fa_carry(A[3], B[3], fa_carry(A[2], B[2], fa_carry(A[1], B[1], fa_carry(A[0], B[0], C_in))))
    );

endmodule