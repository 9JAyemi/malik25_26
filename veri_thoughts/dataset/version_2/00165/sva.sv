module four_bit_adder_sva (
    input logic clk,
    input logic [3:0] A,
    input logic [3:0] B,
    input logic [3:0] S,
    input logic C_out
);

    // The 5-bit output value matches unsigned addition of A and B.
    check_total_sum: assert property (
        @(posedge clk)
        {C_out, S} == ({1'b0, A} + {1'b0, B})
    );

    // Carry-out is asserted exactly when the 4-bit addition overflows.
    check_carry_out_matches_overflow: assert property (
        @(posedge clk)
        C_out == (({1'b0, A} + {1'b0, B}) >= 5'h10)
    );

    // Bit 0 sum is the XOR of the least-significant input bits.
    check_lsb_sum: assert property (
        @(posedge clk)
        S[0] == (A[0] ^ B[0])
    );

    // Bit 1 sum includes the carry generated by bit 0.
    check_bit1_sum: assert property (
        @(posedge clk)
        S[1] == (A[1] ^ B[1] ^ (A[0] & B[0]))
    );

    // Bit 2 sum includes the ripple carry from the lower two bits.
    check_bit2_sum: assert property (
        @(posedge clk)
        S[2] == (A[2] ^ B[2] ^
                 ((A[1] & B[1]) |
                  (A[1] & (A[0] & B[0])) |
                  (B[1] & (A[0] & B[0]))))
    );

    // Zero on A passes B through with no carry.
    check_a_zero_passthrough: assert property (
        @(posedge clk)
        (A == 4'h0) |-> ({C_out, S} == {1'b0, B})
    );

    // Zero on B passes A through with no carry.
    check_b_zero_passthrough: assert property (
        @(posedge clk)
        (B == 4'h0) |-> ({C_out, S} == {1'b0, A})
    );

    // Two operands with clear MSBs cannot produce an overflow carry.
    check_no_overflow_small_operands: assert property (
        @(posedge clk)
        (!A[3] && !B[3]) |-> (C_out == 1'b0)
    );

endmodule