module four_bit_adder_sva (
    input logic clk,
    input logic [3:0] A,
    input logic [3:0] B,
    input logic Cout,
    input logic [3:0] S
);

    function automatic logic maj3(input logic a, input logic b, input logic c);
        maj3 = (a & b) | (b & c) | (a & c);
    endfunction

    // The concatenated outputs equal the 5-bit sum of A and B.
    check_full_sum: assert property (
        @(posedge clk) {Cout, S} == ({1'b0, A} + {1'b0, B})
    );

    // Sum bit 0 is the xor of the least-significant input bits.
    check_sum_bit0: assert property (
        @(posedge clk) S[0] == (A[0] ^ B[0])
    );

    // Sum bit 1 includes the carry generated by bit 0.
    check_sum_bit1: assert property (
        @(posedge clk) S[1] == (A[1] ^ B[1] ^ (A[0] & B[0]))
    );

    // Sum bit 2 includes the majority carry from bit 1.
    check_sum_bit2: assert property (
        @(posedge clk) S[2] == (A[2] ^ B[2] ^ maj3(A[1], B[1], (A[0] & B[0])))
    );

    // Sum bit 3 includes the majority carry from bit 2.
    check_sum_bit3: assert property (
        @(posedge clk) S[3] == (A[3] ^ B[3] ^ maj3(A[2], B[2], maj3(A[1], B[1], (A[0] & B[0]))))
    );

    // Cout is the majority of the top input bits and the carry into bit 3.
    check_cout: assert property (
        @(posedge clk) Cout == maj3(A[3], B[3], maj3(A[2], B[2], maj3(A[1], B[1], (A[0] & B[0]))))
    );

endmodule