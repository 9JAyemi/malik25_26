module top_module_sva(
    input logic clk,
    input logic [3:0] a,
    input logic [3:0] b,
    input logic [3:0] c,
    input logic [3:0] sum,
    input logic carry_out,
    input logic [3:0] result
);

    // No reset exists in the RTL; clk is a sampling clock for these checks.

    wire c1_exp;
    wire c2_exp;
    wire carry_out_exp;
    wire [3:0] s1_exp;
    wire s1_add5_c0_exp;
    wire s1_add5_c1_exp;
    wire s1_add5_c2_exp;
    wire [3:0] sum_exp;
    wire sum_add5_c0_exp;
    wire sum_add5_c1_exp;
    wire sum_add5_c2_exp;
    wire [3:0] result_exp;

    assign c1_exp = (a[0] & b[0]) | (a[0] & c[0]) | (b[0] & c[0]);
    assign c2_exp = (a[1] & b[1]) | (a[1] & c1_exp) | (b[1] & c1_exp);
    assign carry_out_exp = (a[2] & b[2]) | (a[2] & c2_exp) | (b[2] & c2_exp);

    assign s1_exp[0] = a[0] ^ b[0] ^ c[0];
    assign s1_exp[1] = a[1] ^ b[1] ^ c1_exp;
    assign s1_exp[2] = a[2] ^ b[2] ^ c2_exp;
    assign s1_exp[3] = a[3] ^ b[3] ^ carry_out_exp;

    assign s1_add5_c0_exp = s1_exp[0];
    assign s1_add5_c1_exp = s1_exp[1] & s1_exp[0];
    assign s1_add5_c2_exp = s1_exp[2] | s1_add5_c1_exp;
    assign sum_exp = s1_exp + 4'b0101;

    assign sum_add5_c0_exp = sum[0];
    assign sum_add5_c1_exp = sum[1] & sum[0];
    assign sum_add5_c2_exp = sum[2] | sum_add5_c1_exp;
    assign result_exp = sum_exp + 4'b0101;

    // carry_out is the carry generated by the third full adder.
    check_carry_out_function: assert property (
        @(posedge clk) carry_out == carry_out_exp
    );

    // sum matches the ripple-carry output after the first +5.
    check_sum_bus_function: assert property (
        @(posedge clk) sum == sum_exp
    );

    // result is sum passed through the top-level add_5 instance.
    check_result_matches_sum_plus_five: assert property (
        @(posedge clk) result == (sum + 4'b0101)
    );

    // result matches the full end-to-end combinational function.
    check_result_bus_function: assert property (
        @(posedge clk) result == result_exp
    );

    // sum[0] is the raw ripple LSB toggled by the first +5.
    check_sum_bit0_function: assert property (
        @(posedge clk) sum[0] == (s1_exp[0] ^ 1'b1)
    );

    // sum[1] includes the carry from bit 0 of the first +5.
    check_sum_bit1_function: assert property (
        @(posedge clk) sum[1] == (s1_exp[1] ^ s1_add5_c0_exp)
    );

    // sum[2] includes the constant bit-2 add and carry from bit 1.
    check_sum_bit2_function: assert property (
        @(posedge clk) sum[2] == (s1_exp[2] ^ 1'b1 ^ s1_add5_c1_exp)
    );

    // sum[3] includes the carry propagated through bit 2 of the first +5.
    check_sum_bit3_function: assert property (
        @(posedge clk) sum[3] == (s1_exp[3] ^ s1_add5_c2_exp)
    );

    // result[0] is sum[0] toggled by the second +5.
    check_result_bit0_function: assert property (
        @(posedge clk) result[0] == (sum[0] ^ 1'b1)
    );

    // result[1] includes the carry from bit 0 of the second +5.
    check_result_bit1_function: assert property (
        @(posedge clk) result[1] == (sum[1] ^ sum_add5_c0_exp)
    );

    // result[2] includes the constant bit-2 add and carry from bit 1.
    check_result_bit2_function: assert property (
        @(posedge clk) result[2] == (sum[2] ^ 1'b1 ^ sum_add5_c1_exp)
    );

    // result[3] includes the carry propagated through bit 2 of the second +5.
    check_result_bit3_function: assert property (
        @(posedge clk) result[3] == (sum[3] ^ sum_add5_c2_exp)
    );

endmodule