module adder4_sva (
    input logic        clk,
    input logic [3:0]  a,
    input logic [3:0]  b,
    input logic        cin,
    input logic [3:0]  sum,
    input logic        cout
);

    wire [3:0] sum_temp;
    wire [3:0] carry_temp;

    assign sum_temp = a + b + cin;
    assign carry_temp[0] = (a[0] & b[0]) | (a[0] & cin) | (b[0] & cin);
    assign carry_temp[1] = (a[1] & b[1]) | (a[1] & carry_temp[0]) | (b[1] & carry_temp[0]);
    assign carry_temp[2] = (a[2] & b[2]) | (a[2] & carry_temp[1]) | (b[2] & carry_temp[1]);
    assign carry_temp[3] = (a[3] & b[3]) | (a[3] & carry_temp[2]) | (b[3] & carry_temp[2]);

    // Sum must match the RTL's 4-bit addition result.
    check_sum_matches_sum_temp: assert property (
        @(posedge clk) sum == sum_temp
    );

    // Carry-out must match the final ripple-carry stage.
    check_cout_matches_carry_temp3: assert property (
        @(posedge clk) cout == carry_temp[3]
    );

    // Combined outputs must equal the 5-bit sum of a, b, and cin.
    check_full_result_matches_extended_add: assert property (
        @(posedge clk) {cout, sum} == ({1'b0, a} + {1'b0, b} + cin)
    );

    // Sum bit 0 is the parity of a[0], b[0], and cin.
    check_sum_bit0_parity: assert property (
        @(posedge clk) sum[0] == (a[0] ^ b[0] ^ cin)
    );

    // Sum bit 1 uses the carry generated by bit 0.
    check_sum_bit1_uses_carry0: assert property (
        @(posedge clk) sum[1] == (a[1] ^ b[1] ^ carry_temp[0])
    );

    // Sum bit 2 uses the carry generated by bit 1.
    check_sum_bit2_uses_carry1: assert property (
        @(posedge clk) sum[2] == (a[2] ^ b[2] ^ carry_temp[1])
    );

    // Sum bit 3 uses the carry generated by bit 2.
    check_sum_bit3_uses_carry2: assert property (
        @(posedge clk) sum[3] == (a[3] ^ b[3] ^ carry_temp[2])
    );

endmodule