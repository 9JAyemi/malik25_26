module binary_adder_sva(
    input logic clk,
    input logic [3:0] A,
    input logic [3:0] B,
    input logic [3:0] S,
    input logic C
);

    // External sampling clock; the RTL has no native clock or reset.

    // The 5-bit output value matches the arithmetic sum of A and B.
    check_full_sum: assert property (
        @(posedge clk) ({C, S} == ({1'b0, A} + {1'b0, B}))
    );

    // The lower 4 bits of the arithmetic sum drive S.
    check_sum_lower_bits: assert property (
        @(posedge clk) ({1'b0, S} == (({1'b0, A} + {1'b0, B}) & 5'h0F))
    );

    // Bit 0 has no carry-in, so it is just A[0] xor B[0].
    check_lsb_sum: assert property (
        @(posedge clk) (S[0] == (A[0] ^ B[0]))
    );

    // Bit 1 includes the carry generated by bit 0.
    check_bit1_sum: assert property (
        @(posedge clk) (S[1] == (A[1] ^ B[1] ^ (A[0] & B[0])))
    );

    // Zero plus zero produces zero with no carry.
    check_zero_plus_zero: assert property (
        @(posedge clk) (((A == 4'h0) && (B == 4'h0)) |-> ({C, S} == 5'h00))
    );

    // A equal to zero passes B through with no carry.
    check_a_zero_identity: assert property (
        @(posedge clk) ((A == 4'h0) |-> ({C, S} == {1'b0, B}))
    );

    // B equal to zero passes A through with no carry.
    check_b_zero_identity: assert property (
        @(posedge clk) ((B == 4'h0) |-> ({C, S} == {1'b0, A}))
    );

    // Carry-out is high whenever the 5-bit sum exceeds 4 bits.
    check_carry_on_overflow: assert property (
        @(posedge clk) ((({1'b0, A} + {1'b0, B}) >= 5'h10) |-> (C == 1'b1))
    );

    // Carry-out stays low whenever the sum fits in 4 bits.
    check_no_carry_without_overflow: assert property (
        @(posedge clk) ((({1'b0, A} + {1'b0, B}) < 5'h10) |-> (C == 1'b0))
    );

    // The maximum input case produces decimal 30.
    check_max_plus_max: assert property (
        @(posedge clk) (((A == 4'hF) && (B == 4'hF)) |-> ({C, S} == 5'h1E))
    );

endmodule