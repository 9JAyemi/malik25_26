module Adder(din_a, din_b, din_c, dout);

	////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
	// I/O declarations

	
	input wire[3:0] din_a;

	
	input wire[3:0] din_b;

	
	input wire[3:0] din_c;

	
	output wire[3:0] dout;

	////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
	// The adder

	wire[3:0] sum;
	assign sum = din_a + din_b + din_c;
	assign dout = sum;

endmodule