module four_bit_adder_sva (
    input logic       clk,
    input logic [3:0] A,
    input logic [3:0] B,
    input logic [3:0] S,
    input logic       Cout
);

    // External sampling clock; DUT has no reset and is purely combinational.

    // The 5-bit output must equal the zero-extended sum of A and B.
    check_total_addition: assert property (
        @(posedge clk) {Cout, S} == ({1'b0, A} + {1'b0, B})
    );

    // Sum bit 0 is the XOR of the least-significant input bits.
    check_sum_bit0: assert property (
        @(posedge clk) S[0] == (A[0] ^ B[0])
    );

    // Sum bit 1 uses the carry generated by bit 0.
    check_sum_bit1: assert property (
        @(posedge clk) S[1] == (A[1] ^ B[1] ^ (A[0] & B[0]))
    );

    // Sum bit 2 uses the ripple carry from bits 0 and 1.
    check_sum_bit2: assert property (
        @(posedge clk) S[2] == (A[2] ^ B[2] ^
            ((A[1] & B[1]) | ((A[0] & B[0]) & (A[1] ^ B[1]))))
    );

    // Sum bit 3 uses the ripple carry from bits 0 through 2.
    check_sum_bit3: assert property (
        @(posedge clk) S[3] == (A[3] ^ B[3] ^
            ((A[2] & B[2]) |
             (((A[1] & B[1]) | ((A[0] & B[0]) & (A[1] ^ B[1]))) & (A[2] ^ B[2]))))
    );

    // Carry out is the final ripple carry from the most-significant stage.
    check_carry_out: assert property (
        @(posedge clk) Cout == ((A[3] & B[3]) |
            (((A[2] & B[2]) |
              (((A[1] & B[1]) | ((A[0] & B[0]) & (A[1] ^ B[1]))) & (A[2] ^ B[2])))
             & (A[3] ^ B[3])))
    );

endmodule