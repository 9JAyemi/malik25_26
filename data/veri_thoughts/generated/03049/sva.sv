module adder_8bit_sva (
    input logic        clk,
    input logic [7:0]  A,
    input logic [7:0]  B,
    input logic [7:0]  S,
    input logic        Cout
);

    // Sampling clock for the combinational DUT; no reset exists in the RTL.

    // Entire 9-bit result must match the unsigned sum of A and B.
    check_total_sum: assert property (
        @(posedge clk) {Cout, S} == ({1'b0, A} + {1'b0, B})
    );

    // Bit 0 sum is XOR because the first carry-in is tied low.
    check_lsb_sum: assert property (
        @(posedge clk) S[0] == (A[0] ^ B[0])
    );

    // Bit 1 sum must include the carry generated by bit 0.
    check_bit1_ripple_sum: assert property (
        @(posedge clk) S[1] == (A[1] ^ B[1] ^ (A[0] & B[0]))
    );

    // Adding zero on A must pass B through with no carry.
    check_a_zero_passthrough: assert property (
        @(posedge clk) (A == 8'h00) |-> ({Cout, S} == {1'b0, B})
    );

    // Adding zero on B must pass A through with no carry.
    check_b_zero_passthrough: assert property (
        @(posedge clk) (B == 8'h00) |-> ({Cout, S} == {1'b0, A})
    );

    // Carry-out must indicate overflow of the 8-bit addition.
    check_carry_out: assert property (
        @(posedge clk) Cout == (({1'b0, A} + {1'b0, B}) > 9'h0FF)
    );

endmodule