module adder_overflow_assertions (
    input logic       clk,
    input logic [7:0] a,
    input logic [7:0] b,
    input logic [7:0] s,
    input logic       overflow
);

    // Sum output matches the 8-bit addition of the inputs.
    check_sum_matches_addition: assert property (
        @(posedge clk) s == (a + b)
    );

    // Lower 7 sum bits match the lower 7-bit addition result.
    check_lower_bits_match_addition: assert property (
        @(posedge clk) s[6:0] == (a[6:0] + b[6:0])
    );

    // Overflow output matches the RTL XOR equation.
    check_overflow_matches_xor_equation: assert property (
        @(posedge clk) overflow == (s[7] ^ a[7] ^ b[7])
    );

    // Overflow equals the carry generated by adding the lower 7 bits.
    check_overflow_matches_lower_carry: assert property (
        @(posedge clk) overflow == (({1'b0, a[6:0]} + {1'b0, b[6:0]})[7])
    );

    // A zero on input a passes b through and clears overflow.
    check_a_zero_passthrough: assert property (
        @(posedge clk) (a == 8'h00) |-> ((s == b) && (overflow == 1'b0))
    );

    // A zero on input b passes a through and clears overflow.
    check_b_zero_passthrough: assert property (
        @(posedge clk) (b == 8'h00) |-> ((s == a) && (overflow == 1'b0))
    );

endmodule