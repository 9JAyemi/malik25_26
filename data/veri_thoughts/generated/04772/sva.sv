module four_bit_adder_sva (
    input logic       clk,
    input logic [3:0] A,
    input logic [3:0] B,
    input logic [3:0] S,
    input logic       C_out
);

    // Pure combinational DUT with no RTL reset; sample on external clk.

    // Whole output equals the 5-bit sum of A and B.
    check_total_sum: assert property (
        @(posedge clk) disable iff (1'b0)
        ({C_out, S} == ({1'b0, A} + {1'b0, B}))
    );

    // Bit 0 sum is the XOR of the LSB inputs because cin is tied low.
    check_bit0_sum: assert property (
        @(posedge clk) disable iff (1'b0)
        (S[0] == (A[0] ^ B[0]))
    );

    // Bit 1 sum uses the carry generated by bit 0.
    check_bit1_sum: assert property (
        @(posedge clk) disable iff (1'b0)
        (S[1] == (A[1] ^ B[1] ^ (A[0] & B[0])))
    );

    // Bit 2 sum uses the ripple carry from bit 1.
    check_bit2_sum: assert property (
        @(posedge clk) disable iff (1'b0)
        (S[2] == (
            A[2] ^ B[2] ^
            ((A[1] & B[1]) | ((A[1] | B[1]) & (A[0] & B[0])))
        ))
    );

    // Bit 3 sum uses the ripple carry from bit 2.
    check_bit3_sum: assert property (
        @(posedge clk) disable iff (1'b0)
        (S[3] == (
            A[3] ^ B[3] ^
            ((A[2] & B[2]) | ((A[2] | B[2]) &
                ((A[1] & B[1]) | ((A[1] | B[1]) & (A[0] & B[0])))
            ))
        ))
    );

    // C_out matches the carry-out of the MSB full adder.
    check_final_carry: assert property (
        @(posedge clk) disable iff (1'b0)
        (C_out == (
            (A[3] & B[3]) | ((A[3] | B[3]) &
                ((A[2] & B[2]) | ((A[2] | B[2]) &
                    ((A[1] & B[1]) | ((A[1] | B[1]) & (A[0] & B[0])))
                ))
            )
        ))
    );

endmodule