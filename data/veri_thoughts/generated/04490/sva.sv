module ripple_adder_sva (
    input logic       clk,
    input logic [3:0] a,
    input logic [3:0] b,
    input logic       cin,
    input logic [3:0] s,
    input logic       cout
);

    function automatic logic maj3(
        input logic x,
        input logic y,
        input logic z
    );
        maj3 = (x & y) | (x & z) | (y & z);
    endfunction

    // The 5-bit output matches the 4-bit addition with carry-in.
    check_total_addition: assert property (
        @(posedge clk) {cout, s} == ({1'b0, a} + {1'b0, b} + cin)
    );

    // Sum bit 0 is the XOR of the LSB inputs and cin.
    check_sum_bit0: assert property (
        @(posedge clk) s[0] == (a[0] ^ b[0] ^ cin)
    );

    // Sum bit 1 uses the carry generated by bit 0.
    check_sum_bit1: assert property (
        @(posedge clk) s[1] == (a[1] ^ b[1] ^ maj3(a[0], b[0], cin))
    );

    // Sum bit 2 uses the carry generated by bit 1.
    check_sum_bit2: assert property (
        @(posedge clk) s[2] == (a[2] ^ b[2] ^ maj3(a[1], b[1], maj3(a[0], b[0], cin)))
    );

    // Sum bit 3 uses the carry generated by bit 2.
    check_sum_bit3: assert property (
        @(posedge clk) s[3] == (a[3] ^ b[3] ^ maj3(a[2], b[2], maj3(a[1], b[1], maj3(a[0], b[0], cin))))
    );

    // Cout is the carry out of the MSB stage.
    check_cout: assert property (
        @(posedge clk) cout == maj3(a[3], b[3], maj3(a[2], b[2], maj3(a[1], b[1], maj3(a[0], b[0], cin))))
    );

endmodule